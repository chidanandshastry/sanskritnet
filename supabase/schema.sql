-- =====================================================================
-- UGC NET Sanskrit (Code 25) Mock Test - database setup
-- Paste this whole file into Supabase > SQL Editor > Run (safe to re-run).
--
-- Security design:
--   * Students can NEVER read the questions table directly (so correct
--     answers cannot be seen before submitting).
--   * Tests are issued by start_test() and marked by submit_attempt()
--     on the server. Scores cannot be faked from the browser.
-- Marking: +2 per correct answer, no negative marking (UGC NET pattern).
-- Time allowed: 72 seconds per question (100 questions = 120 minutes).
-- =====================================================================

-- ---------- Tables ----------------------------------------------------
create table if not exists public.units (
  id    int primary key,
  title text not null
);

insert into public.units (id, title)
select g, 'Unit ' || g from generate_series(1, 10) g
on conflict (id) do nothing;

create table if not exists public.questions (
  id          int generated by default as identity primary key,
  unit        int not null references public.units(id),
  question    text not null,
  option_a    text not null,
  option_b    text not null,
  option_c    text not null,
  option_d    text not null,
  correct     text not null check (correct in ('A','B','C','D')),
  explanation text
);
create index if not exists questions_unit_idx on public.questions(unit);

create table if not exists public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  name       text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.test_sessions (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null references auth.users(id) on delete cascade,
  unit         int references public.units(id),     -- null = full mock
  question_ids int[] not null,
  started_at   timestamptz not null default now(),
  submitted    boolean not null default false
);

create table if not exists public.attempts (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references auth.users(id) on delete cascade,
  session_id   uuid unique references public.test_sessions(id),
  unit         int references public.units(id),     -- null = full mock
  total        int not null,
  correct      int not null,
  wrong        int not null,
  unattempted  int not null,
  score        int not null,
  answers      jsonb not null default '{}'::jsonb,
  question_ids int[] not null,
  duration_sec int not null,
  late         boolean not null default false,
  created_at   timestamptz not null default now()
);
create index if not exists attempts_user_idx on public.attempts(user_id, created_at desc);

-- ---------- Row level security ---------------------------------------
alter table public.units         enable row level security;
alter table public.questions     enable row level security;
alter table public.profiles      enable row level security;
alter table public.test_sessions enable row level security;
alter table public.attempts      enable row level security;

drop policy if exists "units readable"    on public.units;
drop policy if exists "own profile read"  on public.profiles;
drop policy if exists "own attempts read" on public.attempts;

create policy "units readable"    on public.units    for select to authenticated using (true);
create policy "own profile read"  on public.profiles for select to authenticated using (id = auth.uid());
create policy "own attempts read" on public.attempts for select to authenticated using (user_id = auth.uid());
-- questions and test_sessions: no policies = no direct access for students.

revoke all on public.questions     from anon, authenticated;
revoke all on public.test_sessions from anon, authenticated;
revoke all on public.profiles      from anon;
revoke all on public.attempts      from anon;
revoke insert, update, delete on public.attempts from authenticated;
revoke insert, update, delete on public.profiles from authenticated;
revoke insert, update, delete on public.units    from authenticated;

-- ---------- Auto-create profile on sign up ---------------------------
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, name)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data->>'name'), ''), split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- Functions used by the website -----------------------------

-- How many questions each unit has.
create or replace function public.unit_counts()
returns table(id int, title text, n bigint)
language sql security definer stable set search_path = public as $$
  select u.id, u.title, count(q.id)
  from public.units u left join public.questions q on q.unit = u.id
  group by u.id, u.title
  order by u.id;
$$;

-- Start a test. p_unit = null gives a full mock (balanced across units).
-- Returns questions WITHOUT correct answers.
create or replace function public.start_test(p_unit int default null, p_count int default 100)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_n   int := greatest(1, least(coalesce(p_count, 100), 100));
  v_ids int[];
  v_sid uuid;
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;

  if p_unit is null then
    -- up to ceil(n/10) from every unit first, then fill the rest randomly
    select array_agg(t.id) into v_ids from (
      select s.id from (
        select q.id, row_number() over (partition by q.unit order by random()) as rn
        from public.questions q
      ) s
      order by (s.rn <= ceil(v_n / 10.0)) desc, random()
      limit v_n
    ) t;
  else
    select array_agg(t.id) into v_ids from (
      select q.id from public.questions q where q.unit = p_unit order by random() limit v_n
    ) t;
  end if;

  if v_ids is null then raise exception 'No questions available yet for this test'; end if;

  insert into public.test_sessions (user_id, unit, question_ids)
  values (auth.uid(), p_unit, v_ids)
  returning id into v_sid;

  return jsonb_build_object(
    'session_id', v_sid,
    'unit', p_unit,
    'questions', (
      select jsonb_agg(
        jsonb_build_object('id', q.id, 'unit', q.unit, 'question', q.question,
                           'a', q.option_a, 'b', q.option_b, 'c', q.option_c, 'd', q.option_d)
        order by array_position(v_ids, q.id))
      from public.questions q where q.id = any(v_ids)
    )
  );
end $$;

-- Full result + answer review of one attempt (only the owner can read it).
create or replace function public.get_attempt_review(p_attempt_id bigint)
returns jsonb language plpgsql security definer stable set search_path = public as $$
declare att public.attempts%rowtype;
begin
  select * into att from public.attempts where id = p_attempt_id and user_id = auth.uid();
  if not found then raise exception 'Attempt not found'; end if;

  return jsonb_build_object(
    'attempt_id', att.id, 'unit', att.unit, 'total', att.total, 'correct', att.correct,
    'wrong', att.wrong, 'unattempted', att.unattempted, 'score', att.score,
    'max_score', att.total * 2, 'duration_sec', att.duration_sec, 'late', att.late,
    'review', (
      select coalesce(jsonb_agg(
        jsonb_build_object('id', q.id, 'unit', q.unit, 'question', q.question,
          'a', q.option_a, 'b', q.option_b, 'c', q.option_c, 'd', q.option_d,
          'correct', q.correct, 'chosen', att.answers->>(q.id::text),
          'explanation', q.explanation)
        order by array_position(att.question_ids, q.id)), '[]'::jsonb)
      from public.questions q where q.id = any(att.question_ids)
    )
  );
end $$;

-- Submit answers: p_answers looks like {"12":"A","15":"C"}. Marked on the server.
create or replace function public.submit_attempt(p_session uuid, p_answers jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  s          public.test_sessions%rowtype;
  v_ans      jsonb := coalesce(p_answers, '{}'::jsonb);
  v_total    int;
  v_correct  int;
  v_answered int;
  v_dur      int;
  v_late     boolean;
  v_aid      bigint;
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;
  if jsonb_typeof(v_ans) <> 'object' or pg_column_size(v_ans) > 20000 then
    raise exception 'Invalid answers';
  end if;

  select * into s from public.test_sessions
   where id = p_session and user_id = auth.uid() for update;
  if not found then raise exception 'Test session not found'; end if;
  if s.submitted then raise exception 'This test was already submitted'; end if;

  v_total := array_length(s.question_ids, 1);

  select count(*) filter (where v_ans->>(q.id::text) = q.correct),
         count(*) filter (where v_ans->>(q.id::text) in ('A','B','C','D'))
    into v_correct, v_answered
    from public.questions q where q.id = any(s.question_ids);

  v_dur  := extract(epoch from (now() - s.started_at))::int;
  v_late := v_dur > v_total * 72 + 120;      -- allowed time + 2 min grace

  update public.test_sessions set submitted = true where id = s.id;

  insert into public.attempts
    (user_id, session_id, unit, total, correct, wrong, unattempted, score,
     answers, question_ids, duration_sec, late)
  values
    (auth.uid(), s.id, s.unit, v_total, v_correct, v_answered - v_correct,
     v_total - v_answered, v_correct * 2, v_ans, s.question_ids, v_dur, v_late)
  returning id into v_aid;

  return public.get_attempt_review(v_aid);
end $$;

-- Leaderboard: best attempt per student. p_unit = null is the full mock.
create or replace function public.get_leaderboard(p_unit int default null)
returns table(rank bigint, name text, best_score int, best_pct numeric, attempts bigint)
language sql security definer stable set search_path = public as $$
  with per_user as (
    select a.user_id,
           max(a.score) as best_score,
           max(round(100.0 * a.score / nullif(a.total * 2, 0), 1)) as best_pct,
           count(*) as attempts
    from public.attempts a
    where a.unit is not distinct from p_unit and not a.late
    group by a.user_id
  )
  select row_number() over (order by u.best_pct desc, u.best_score desc, p.name)::bigint,
         coalesce(p.name, 'Student'), u.best_score, u.best_pct, u.attempts
  from per_user u left join public.profiles p on p.id = u.user_id
  order by 1
  limit 50;
$$;

-- ---------- Who may call what -----------------------------------------
revoke execute on function public.unit_counts()                  from public, anon;
revoke execute on function public.start_test(int, int)           from public, anon;
revoke execute on function public.get_attempt_review(bigint)     from public, anon;
revoke execute on function public.submit_attempt(uuid, jsonb)    from public, anon;
revoke execute on function public.get_leaderboard(int)           from public, anon;
grant  execute on function public.unit_counts()                  to authenticated;
grant  execute on function public.start_test(int, int)           to authenticated;
grant  execute on function public.get_attempt_review(bigint)     to authenticated;
grant  execute on function public.submit_attempt(uuid, jsonb)    to authenticated;
grant  execute on function public.get_leaderboard(int)           to authenticated;
