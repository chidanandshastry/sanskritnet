-- ---------- Test kinds (full mock, unit test, mistakes, saved) ---------
alter table public.test_sessions
  add column if not exists kind text not null default 'unit' check (kind in ('full','unit','mistakes','saved'));
alter table public.attempts
  add column if not exists kind text not null default 'unit' check (kind in ('full','unit','mistakes','saved'));
update public.test_sessions set kind = 'full' where unit is null and kind = 'unit';
update public.attempts      set kind = 'full' where unit is null and kind = 'unit';
create index if not exists attempts_qids_gin on public.attempts using gin (question_ids);

-- ---------- Saved questions and reports -------------------------------
create table if not exists public.bookmarks (
  user_id     uuid not null references auth.users(id) on delete cascade,
  question_id int  not null references public.questions(id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (user_id, question_id)
);

create table if not exists public.question_reports (
  id          bigint generated by default as identity primary key,
  question_id int  not null references public.questions(id) on delete cascade,
  user_id     uuid not null references auth.users(id) on delete cascade,
  reason      text not null check (reason in ('wrong_answer','unclear','typo','other')),
  note        text,
  status      text not null default 'open' check (status in ('open','resolved')),
  created_at  timestamptz not null default now()
);
create unique index if not exists one_open_report on public.question_reports (question_id, user_id) where status = 'open';

alter table public.bookmarks        enable row level security;
alter table public.question_reports enable row level security;
revoke all on public.bookmarks        from anon, authenticated;
revoke all on public.question_reports from anon, authenticated;

-- ---------- Internal helpers (not callable from the website) ----------
create or replace function public.has_seen(p_q int)
returns boolean language sql security definer stable set search_path = public as $$
  select exists (select 1 from public.test_sessions s where s.user_id = auth.uid() and p_q = any(s.question_ids));
$$;

-- Questions whose latest answer by this student was wrong or skipped.
create or replace function public.mistake_ids()
returns setof int language sql security definer stable set search_path = public as $$
  select l.qid from (
    select distinct on (qid) qid, a.answers->>(qid::text) as chosen
    from public.attempts a cross join lateral unnest(a.question_ids) as qid
    where a.user_id = auth.uid()
    order by qid, a.created_at desc) l
  join public.questions q on q.id = l.qid
  where l.chosen is distinct from q.correct;
$$;
revoke execute on function public.has_seen(int)  from public, anon, authenticated;
revoke execute on function public.mistake_ids()  from public, anon, authenticated;

-- ---------- Student functions -----------------------------------------
create or replace function public.report_question(p_question_id int, p_reason text, p_note text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;
  if p_reason not in ('wrong_answer','unclear','typo','other') then raise exception 'Choose a reason'; end if;
  if not public.has_seen(p_question_id) then raise exception 'You can only report questions you have seen in a test'; end if;
  insert into public.question_reports (question_id, user_id, reason, note)
  values (p_question_id, auth.uid(), p_reason, nullif(left(trim(coalesce(p_note, '')), 500), ''))
  on conflict (question_id, user_id) where status = 'open'
  do update set reason = excluded.reason, note = excluded.note, created_at = now();
end $$;

create or replace function public.toggle_bookmark(p_question_id int)
returns boolean language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;
  if exists (select 1 from public.bookmarks where user_id = auth.uid() and question_id = p_question_id) then
    delete from public.bookmarks where user_id = auth.uid() and question_id = p_question_id;
    return false;
  end if;
  if not public.has_seen(p_question_id) then raise exception 'You can only save questions you have seen in a test'; end if;
  insert into public.bookmarks (user_id, question_id) values (auth.uid(), p_question_id);
  return true;
end $$;

create or replace function public.get_bookmark_ids()
returns int[] language sql security definer stable set search_path = public as $$
  select coalesce(array_agg(question_id), '{}') from public.bookmarks where user_id = auth.uid();
$$;

create or replace function public.practice_counts()
returns jsonb language sql security definer stable set search_path = public as $$
  select jsonb_build_object(
    'mistakes', (select count(*) from public.mistake_ids()),
    'saved',    (select count(*) from public.bookmarks b join public.questions q on q.id = b.question_id where b.user_id = auth.uid()));
$$;

-- ---------- start_test with kinds -------------------------------------
drop function if exists public.start_test(int, int);
create or replace function public.start_test(p_unit int default null, p_count int default 100, p_kind text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_n    int  := greatest(1, least(coalesce(p_count, 100), 100));
  v_kind text := coalesce(p_kind, case when p_unit is null then 'full' else 'unit' end);
  v_ids  int[];
  v_sid  uuid;
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;
  if v_kind not in ('full','unit','mistakes','saved') then raise exception 'Unknown test type'; end if;

  if v_kind = 'full' then
    select array_agg(t.id) into v_ids from (
      select s.id from (
        select q.id, row_number() over (partition by q.unit order by random()) as rn from public.questions q
      ) s
      order by (s.rn <= ceil(v_n / 10.0)) desc, random()
      limit v_n) t;
  elsif v_kind = 'unit' then
    if p_unit is null then raise exception 'Choose a unit'; end if;
    select array_agg(t.id) into v_ids from (
      select q.id from public.questions q where q.unit = p_unit order by random() limit v_n) t;
  elsif v_kind = 'mistakes' then
    select array_agg(t.id) into v_ids from (
      select q.id from public.questions q where q.id in (select public.mistake_ids()) order by random() limit v_n) t;
    if v_ids is null then raise exception 'No mistakes to practise yet. Take a test first.'; end if;
  else
    select array_agg(t.id) into v_ids from (
      select q.id from public.questions q join public.bookmarks b on b.question_id = q.id and b.user_id = auth.uid()
      order by random() limit v_n) t;
    if v_ids is null then raise exception 'You have not saved any questions yet.'; end if;
  end if;

  if v_ids is null then raise exception 'No questions available yet for this test'; end if;

  insert into public.test_sessions (user_id, unit, kind, question_ids)
  values (auth.uid(), case when v_kind = 'unit' then p_unit else null end, v_kind, v_ids)
  returning id into v_sid;

  return jsonb_build_object(
    'session_id', v_sid, 'unit', case when v_kind = 'unit' then p_unit else null end, 'kind', v_kind,
    'questions', (
      select jsonb_agg(
        jsonb_build_object('id', q.id, 'unit', q.unit, 'question', q.question,
                           'a', q.option_a, 'b', q.option_b, 'c', q.option_c, 'd', q.option_d)
        order by array_position(v_ids, q.id))
      from public.questions q where q.id = any(v_ids)));
end $$;

-- ---------- submit / review: carry the kind ---------------------------
create or replace function public.get_attempt_review(p_attempt_id bigint)
returns jsonb language plpgsql security definer stable set search_path = public as $$
declare att public.attempts%rowtype;
begin
  select * into att from public.attempts where id = p_attempt_id and user_id = auth.uid();
  if not found then raise exception 'Attempt not found'; end if;
  return jsonb_build_object(
    'attempt_id', att.id, 'unit', att.unit, 'kind', att.kind, 'total', att.total, 'correct', att.correct,
    'wrong', att.wrong, 'unattempted', att.unattempted, 'score', att.score,
    'max_score', att.total * 2, 'duration_sec', att.duration_sec, 'late', att.late,
    'review', (
      select coalesce(jsonb_agg(
        jsonb_build_object('id', q.id, 'unit', q.unit, 'question', q.question,
          'a', q.option_a, 'b', q.option_b, 'c', q.option_c, 'd', q.option_d,
          'correct', q.correct, 'chosen', att.answers->>(q.id::text),
          'explanation', q.explanation)
        order by array_position(att.question_ids, q.id)), '[]'::jsonb)
      from public.questions q where q.id = any(att.question_ids)));
end $$;

create or replace function public.submit_attempt(p_session uuid, p_answers jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  s public.test_sessions%rowtype;
  v_ans jsonb := coalesce(p_answers, '{}'::jsonb);
  v_total int; v_correct int; v_answered int; v_dur int; v_late boolean; v_aid bigint;
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;
  if jsonb_typeof(v_ans) <> 'object' or pg_column_size(v_ans) > 20000 then raise exception 'Invalid answers'; end if;

  select * into s from public.test_sessions where id = p_session and user_id = auth.uid() for update;
  if not found then raise exception 'Test session not found'; end if;
  if s.submitted then raise exception 'This test was already submitted'; end if;

  v_total := array_length(s.question_ids, 1);
  select count(*) filter (where v_ans->>(q.id::text) = q.correct),
         count(*) filter (where v_ans->>(q.id::text) in ('A','B','C','D'))
    into v_correct, v_answered
    from public.questions q where q.id = any(s.question_ids);

  v_dur  := extract(epoch from (now() - s.started_at))::int;
  v_late := v_dur > v_total * 72 + 120;

  update public.test_sessions set submitted = true where id = s.id;
  insert into public.attempts
    (user_id, session_id, unit, kind, total, correct, wrong, unattempted, score, answers, question_ids, duration_sec, late)
  values
    (auth.uid(), s.id, s.unit, s.kind, v_total, v_correct, v_answered - v_correct,
     v_total - v_answered, v_correct * 2, v_ans, s.question_ids, v_dur, v_late)
  returning id into v_aid;
  return public.get_attempt_review(v_aid);
end $$;

-- ---------- leaderboard and stats: only real full mocks / unit tests ---
create or replace function public.get_leaderboard(p_unit int default null)
returns table(rank bigint, name text, best_score int, best_pct numeric, attempts bigint)
language sql security definer stable set search_path = public as $$
  with per_user as (
    select a.user_id, max(a.score) as best_score,
           max(round(100.0 * a.score / nullif(a.total * 2, 0), 1)) as best_pct, count(*) as attempts
    from public.attempts a
    where not a.late
      and case when p_unit is null then a.kind = 'full' else (a.kind = 'unit' and a.unit = p_unit) end
    group by a.user_id)
  select row_number() over (order by u.best_pct desc, u.best_score desc, p.name)::bigint,
         coalesce(p.name, 'Student'), u.best_score, u.best_pct, u.attempts
  from per_user u left join public.profiles p on p.id = u.user_id
  order by 1 limit 50;
$$;

create or replace function public.my_stats()
returns jsonb language plpgsql security definer stable set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_attempts int; v_avg numeric; v_best numeric; v_streak int := 0;
  v_answered int := 0; v_correct int := 0;
  v_rank int; v_players int; v_units jsonb; v_trend jsonb;
begin
  if v_uid is null then raise exception 'Please log in first'; end if;

  select count(*), round(avg(100.0 * score / nullif(total * 2, 0)), 1), max(round(100.0 * score / nullif(total * 2, 0), 1))
    into v_attempts, v_avg, v_best from public.attempts where user_id = v_uid;

  select coalesce(jsonb_agg(jsonb_build_object('unit', x.unit, 'answered', x.answered, 'correct', x.correct, 'seen', x.seen) order by x.unit), '[]'::jsonb),
         coalesce(sum(x.answered), 0), coalesce(sum(x.correct), 0)
    into v_units, v_answered, v_correct
  from (
    select q.unit, count(*) as seen,
           count(*) filter (where a.answers->>(q.id::text) in ('A','B','C','D')) as answered,
           count(*) filter (where a.answers->>(q.id::text) = q.correct) as correct
    from public.attempts a
    cross join lateral unnest(a.question_ids) as qid
    join public.questions q on q.id = qid
    where a.user_id = v_uid group by q.unit) x;

  with d as (select distinct (created_at at time zone 'Asia/Kolkata')::date as day from public.attempts where user_id = v_uid),
       g as (select day, day - (row_number() over (order by day))::int as grp from d),
       isl as (select count(*) as n, max(day) as last_day from g group by grp)
  select coalesce(max(n) filter (where last_day >= (now() at time zone 'Asia/Kolkata')::date - 1), 0) into v_streak from isl;

  with per_user as (
    select user_id, max(round(100.0 * score / nullif(total * 2, 0), 1)) as best
    from public.attempts where kind = 'full' and not late group by user_id)
  select (select count(*) + 1 from per_user o where o.best > m.best)::int, (select count(*) from per_user)::int
    into v_rank, v_players from per_user m where m.user_id = v_uid;

  select coalesce(jsonb_agg(t order by t.created_at), '[]'::jsonb) into v_trend from (
    select unit, kind, round(100.0 * score / nullif(total * 2, 0), 1) as pct, created_at
    from public.attempts where user_id = v_uid order by created_at desc limit 10) t;

  return jsonb_build_object(
    'attempts', v_attempts, 'avg_pct', v_avg, 'best_pct', v_best, 'streak', v_streak,
    'answered', v_answered, 'correct', v_correct,
    'units', v_units, 'trend', v_trend, 'rank', v_rank, 'players', v_players);
end $$;

-- ---------- Admin: overview, question accuracy, reports ---------------
create or replace function public.admin_stats()
returns jsonb language plpgsql security definer stable set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  return jsonb_build_object(
    'students',     (select count(*) from public.profiles),
    'attempts',     (select count(*) from public.attempts),
    'attempts_7d',  (select count(*) from public.attempts where created_at > now() - interval '7 days'),
    'questions',    (select count(*) from public.questions),
    'open_reports', (select count(*) from public.question_reports where status = 'open'),
    'units', (select coalesce(jsonb_agg(jsonb_build_object('id', x.id, 'title', x.title, 'n', x.n) order by x.id), '[]'::jsonb)
              from (select u.id, u.title, count(q.id) n from public.units u
                    left join public.questions q on q.unit = u.id group by u.id, u.title) x),
    'recent', (select coalesce(jsonb_agg(r), '[]'::jsonb) from (
                 select coalesce(p.name, 'Student') as name, a.unit, a.kind, a.score, a.total, a.created_at
                 from public.attempts a left join public.profiles p on p.id = a.user_id
                 order by a.created_at desc limit 10) r));
end $$;

drop function if exists public.admin_list_questions(int, text, int, int);
create or replace function public.admin_list_questions(
  p_unit int default null, p_search text default null, p_limit int default 25, p_offset int default 0, p_id int default null)
returns jsonb language plpgsql security definer stable set search_path = public as $$
declare v_total bigint; v_rows jsonb; v_s text := nullif(trim(coalesce(p_search, '')), '');
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  select count(*) into v_total from public.questions q
   where (p_id is null or q.id = p_id) and (p_unit is null or q.unit = p_unit)
     and (v_s is null or q.question ilike '%' || v_s || '%');
  select coalesce(jsonb_agg(to_jsonb(r) order by r.id desc), '[]'::jsonb) into v_rows from (
    select q.id, q.unit, q.question, q.option_a, q.option_b, q.option_c, q.option_d, q.correct, q.explanation,
           (select count(*) from public.attempts a where a.question_ids @> array[q.id]) as seen,
           (select count(*) from public.attempts a where a.question_ids @> array[q.id] and a.answers->>(q.id::text) = q.correct) as right_count,
           (select count(*) from public.question_reports r2 where r2.question_id = q.id and r2.status = 'open') as open_reports
    from public.questions q
    where (p_id is null or q.id = p_id) and (p_unit is null or q.unit = p_unit)
      and (v_s is null or q.question ilike '%' || v_s || '%')
    order by q.id desc
    limit greatest(1, least(p_limit, 100)) offset greatest(0, p_offset)) r;
  return jsonb_build_object('total', v_total, 'rows', v_rows);
end $$;

create or replace function public.admin_list_reports(p_status text default 'open')
returns jsonb language plpgsql security definer stable set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  return (select coalesce(jsonb_agg(to_jsonb(r) order by r.created_at desc), '[]'::jsonb) from (
    select rp.id, rp.question_id, rp.reason, rp.note, rp.status, rp.created_at,
           coalesce(p.name, 'Student') as student, q.question, q.correct,
           (select count(*) from public.question_reports x where x.question_id = rp.question_id and x.status = 'open') as open_for_question
    from public.question_reports rp
    join public.questions q on q.id = rp.question_id
    left join public.profiles p on p.id = rp.user_id
    where rp.status = coalesce(p_status, 'open')
    order by rp.created_at desc limit 200) r);
end $$;

create or replace function public.admin_resolve_report(p_id bigint, p_status text default 'resolved')
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  if p_status not in ('open','resolved') then raise exception 'Invalid status'; end if;
  update public.question_reports set status = p_status where id = p_id;
end $$;

